test_that("block counts include directed edges, loops, and parallel edges", {
  g <- graph_create(4)
  graph_add_edges(g, rbind(c(1, 2), c(1, 2), c(2, 1), c(3, 3)))
  s <- block_state(g, c(7, 2, 7, 2))
  expect_equal(block_membership(s), c(7L, 2L, 7L, 2L))
  expect_equal(block_sizes(s), c("2" = 2, "7" = 2))
  expect_equal(unname(block_edge_counts(s)), matrix(c(0, 2, 1, 1), 2))
  graph_add_edges(g, matrix(c(4, 3), ncol = 2))
  expect_equal(sum(block_edge_counts(s)), 4)
})

test_that("undirected block counts count all half-edges", {
  g <- graph_create(3, directed = FALSE)
  graph_add_edges(g, rbind(c(1, 2), c(2, 1), c(1, 1), c(3, 2)))
  s <- block_state(g, c(1, 1, 4))
  expect_equal(unname(block_edge_counts(s)), matrix(c(6, 1, 1, 0), 2))
  expect_equal(sum(block_edge_counts(s)), 2 * graph_num_edges(g))
})

test_that("conditional likelihood matches hand-calculated small graphs", {
  directed <- graph_create(2)
  graph_add_edges(directed, matrix(c(1, 2), ncol = 2))
  expect_equal(block_log_likelihood(block_state(directed, degree_corrected = FALSE)), log(1 / 4))
  expect_equal(block_log_likelihood(block_state(directed)), 0)
  undirected <- graph_create(2, directed = FALSE)
  graph_add_edges(undirected, matrix(c(1, 2), ncol = 2))
  expect_equal(block_log_likelihood(block_state(undirected, degree_corrected = FALSE)), log(1 / 2))
  expect_equal(block_log_likelihood(block_state(undirected)), 0)
  loops <- graph_create(1, directed = FALSE)
  graph_add_edges(loops, rbind(c(1, 1), c(1, 1)))
  expect_equal(block_log_likelihood(block_state(loops)), 0, tolerance = 1e-12)
  expect_equal(block_log_likelihood(block_state(loops, degree_corrected = FALSE)), 0, tolerance = 1e-12)
})

test_that("empty and invalid partitions are handled explicitly", {
  empty <- block_state(graph_create())
  expect_equal(dim(block_edge_counts(empty)), c(0L, 0L))
  expect_equal(block_log_likelihood(empty), 0)
  g <- graph_create(2)
  expect_error(block_state(g, c(1, NA)), "one positive integer")
  expect_error(block_state(g, c(1, 0)), "one positive integer")
  expect_error(block_state(g, 1), "one positive integer")
  expect_error(block_state(g, degree_corrected = NA), "degree_corrected")
})
